// dock-sw.js — Self-uninstalling Service Worker to ensure OBS Browser Source Overlays remain 100% transparent
self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(keys.map((k) => caches.delete(k)));
    }).then(() => {
      return self.registration.unregister();
    }).then(() => {
      return self.clients.claim();
    })
  );
});

// No fetch listener: all network requests pass through normally so overlays never show offline cards
